/**
 * gen-abi.ts - generate src/contract.ts (the QuantumVault ABI) from the
 * Hardhat artifact. Run after `npm run compile`.
 */
import fs from "node:fs";
import path from "node:path";

// npm scripts run with the working directory at the package root.
const root = process.cwd();
const artifactPath = path.resolve(
  root,
  "artifacts",
  "contracts",
  "QuantumVault.sol",
  "QuantumVault.json",
);
if (!fs.existsSync(artifactPath)) {
  throw new Error(`Artifact not found at ${artifactPath}. Run \`npm run compile\` first.`);
}
const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8")) as { abi: unknown };

const out = `// GENERATED by \`npm run gen-abi\` from the Hardhat artifact — do not edit by hand.
export const quantumVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;

fs.writeFileSync(path.resolve(root, "src", "contract.ts"), out);
console.log("Wrote src/contract.ts");
